function translatePage(language) {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue ?? "");
    const source = originalText.get(node) ?? "";
    const content = source.trim().replace(/\s+/g, " ");
    if (!content) continue;
    const leading = source.match(/^\s*/)?.[0] ?? "";
    const trailing = source.match(/\s*$/)?.[0] ?? "";
    const translated = language === "es" ? spanishTranslations[content] : undefined;
    node.nodeValue = translated ? `${leading}${translated}${trailing}` : source;
  }

  const metadata = localizedMetadata[language];
  document.title = metadata.title;
  document.querySelector('meta[name="description"]')?.setAttribute("content", metadata.description);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", metadata.socialTitle);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", metadata.socialDescription);
  document.querySelector('meta[name="twitter:title"]')?.setAttribute("content", metadata.socialTitle);
  document.querySelector('meta[name="twitter:description"]')?.setAttribute("content", metadata.socialDescription);
  document.querySelector(".brand")?.setAttribute("aria-label", language === "es" ? "Inicio de WorkCraft AI" : "WorkCraft AI home");
  document.querySelector(".skip-link")?.setAttribute("href", "#main");
  document.querySelector(".main-nav")?.setAttribute("aria-label", language === "es" ? "Navegación principal" : "Main navigation");
  mobileNavigation?.setAttribute("aria-label", language === "es" ? "Navegación móvil" : "Mobile navigation");
  document.querySelector(".hero-art")?.setAttribute("aria-label", language === "es" ? "Panel ilustrativo de WorkCraft AI con cotizaciones, trabajos, lista de precios e informes ficticios" : "Illustrative WorkCraft AI dashboard with fictional sample estimates, schedule, price book, and reports");
  document.querySelector(".demo-video")?.setAttribute("aria-label", language === "es" ? "Demostración del producto WorkCraft AI" : "WorkCraft AI product demonstration");
  document.querySelectorAll(".brand-image").forEach((image) => image.setAttribute("alt", language === "es" ? "WorkCraft AI, para quienes hacen el trabajo. Mantén el buen trabajo en marcha." : "WorkCraft AI, for the people who get the work done. Keep good work moving."));
  if (languageButton) {
    languageButton.textContent = language === "en" ? "ES" : "EN";
    languageButton.setAttribute("aria-label", language === "en" ? "Switch to Spanish" : "Cambiar a inglés");
  }
  const mockLanguageButton = document.querySelector(".mock-language");
  if (mockLanguageButton) mockLanguageButton.textContent = language === "en" ? "ES" : "EN";
  if (menuButton) {
    const isOpen = menuButton.getAttribute("aria-expanded") === "true";
    menuButton.setAttribute("aria-label", menuLabel(language, isOpen));
  }
}

function menuLabel(language, isOpen) {
  if (language === "es") return isOpen ? "Cerrar menú de navegación" : "Abrir menú de navegación";
  return isOpen ? "Close navigation menu" : "Open navigation menu";
}

let currentLanguage = "en";
try {
  const savedLanguage = localStorage.getItem("workcraftai-marketing-language");
  currentLanguage = savedLanguage === "es" || savedLanguage === "en"
    ? savedLanguage
    : navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
} catch {
  currentLanguage = navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}
translatePage(currentLanguage);
languageButton?.addEventListener("click", () => {
  currentLanguage = currentLanguage === "en" ? "es" : "en";
  try { localStorage.setItem("workcraftai-marketing-language", currentLanguage); } catch {}
  translatePage(currentLanguage);
});

menuButton?.addEventListener("click", () => {
  const isOpen = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!isOpen));
  menuButton.setAttribute("aria-label", menuLabel(currentLanguage, !isOpen));
  mobileNavigation.hidden = isOpen;
});
mobileNavigation?.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  mobileNavigation.hidden = true;
  menuButton?.setAttribute("aria-expanded", "false");
  if (menuButton) menuButton.setAttribute("aria-label", menuLabel(currentLanguage, false));
}));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && mobileNavigation && menuButton) {
    mobileNavigation.hidden = true;
    menuButton.setAttribute("aria-expanded", "false");
    menuButton.setAttribute("aria-label", menuLabel(currentLanguage, false));
  }
});
